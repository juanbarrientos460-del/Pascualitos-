/*
Pascualitos - 03_migrar_datos.sql
Este archivo prepara una zona de staging y controles de calidad.
NO inserta datos históricos automáticamente: primero se debe importar un CSV
depurado desde la hoja "Base De Datos" y mapear sus columnas con el formato
de staging de abajo. No subir el CSV original al repositorio: contiene nombres.
*/
CREATE SCHEMA IF NOT EXISTS pascualitos;
CREATE SCHEMA IF NOT EXISTS pascualitos_staging;

CREATE TABLE IF NOT EXISTS pascualitos_staging.base_datos_excel (
    fila_origen BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE,
    maquina VARCHAR(80),
    operario_nombre VARCHAR(150),
    referencia VARCHAR(150),
    pacas_producidas NUMERIC(12,2),
    horas_trabajadas NUMERIC(8,2),
    turno VARCHAR(80),
    observacion_paro TEXT,
    observaciones TEXT,
    -- Se importan los códigos de paro como texto para respetar ceros/formatos.
    codigo_01 VARCHAR(20), minutos_01 NUMERIC(10,2), subcodigo_01 VARCHAR(30),
    codigo_02 VARCHAR(20), minutos_02 NUMERIC(10,2),
    codigo_03 VARCHAR(20), minutos_03 NUMERIC(10,2), subcodigo_03 VARCHAR(30),
    codigo_04 VARCHAR(20), minutos_04 NUMERIC(10,2),
    codigo_05 VARCHAR(20), minutos_05 NUMERIC(10,2), subcodigo_05 VARCHAR(30),
    codigo_06 VARCHAR(20), minutos_06 NUMERIC(10,2),
    codigo_07 VARCHAR(20), minutos_07 NUMERIC(10,2),
    codigo_08 VARCHAR(20), minutos_08 NUMERIC(10,2),
    codigo_09 VARCHAR(20), minutos_09 NUMERIC(10,2),
    codigo_10 VARCHAR(20), minutos_10 NUMERIC(10,2),
    codigo_11 VARCHAR(20), minutos_11 NUMERIC(10,2),
    codigo_12 VARCHAR(20), minutos_12 NUMERIC(10,2),
    codigo_13 VARCHAR(20), minutos_13 NUMERIC(10,2),
    codigo_14 VARCHAR(20), minutos_14 NUMERIC(10,2),
    codigo_15 VARCHAR(20), minutos_15 NUMERIC(10,2),
    codigo_16 VARCHAR(20), minutos_16 NUMERIC(10,2),
    codigo_17 VARCHAR(20), minutos_17 NUMERIC(10,2),
    codigo_18 VARCHAR(20), minutos_18 NUMERIC(10,2),
    agente VARCHAR(40),
    persona_mantenimiento_nombre VARCHAR(150)
);

-- Controles iniciales después de importar el CSV.
SELECT COUNT(*) AS filas_importadas
FROM pascualitos_staging.base_datos_excel;

SELECT
    COUNT(*) FILTER (WHERE fecha IS NULL) AS fechas_nulas,
    COUNT(*) FILTER (WHERE maquina IS NULL OR BTRIM(maquina) = '') AS maquinas_vacias,
    COUNT(*) FILTER (WHERE pacas_producidas < 0) AS pacas_negativas,
    COUNT(*) FILTER (WHERE horas_trabajadas < 0) AS horas_negativas
FROM pascualitos_staging.base_datos_excel;

-- Valores de máquina/turno que requieren homologación antes de insertar.
SELECT DISTINCT maquina
FROM pascualitos_staging.base_datos_excel
WHERE maquina IS NOT NULL
ORDER BY maquina;

SELECT DISTINCT turno
FROM pascualitos_staging.base_datos_excel
WHERE turno IS NOT NULL
ORDER BY turno;

-- Posibles duplicados exactos de negocio (se investigan; no se borran automáticamente).
SELECT fecha, maquina, operario_nombre, referencia, pacas_producidas,
       horas_trabajadas, turno, COUNT(*) AS repeticiones
FROM pascualitos_staging.base_datos_excel
GROUP BY fecha, maquina, operario_nombre, referencia, pacas_producidas,
         horas_trabajadas, turno
HAVING COUNT(*) > 1
ORDER BY repeticiones DESC;

