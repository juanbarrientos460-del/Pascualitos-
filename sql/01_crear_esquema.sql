/*
Proyecto: Pascualitos – Registro de paros de producción
Motor: PostgreSQL
Archivo: 01_crear_esquema.sql

Ejecutar primero en una base de datos vacía desde DBeaver.
Este script crea el esquema pascualitos y sus tablas.

Decisiones alineadas con docs/03_modelo_conceptual_MER.md,
docs/03_ajustes_entidades.md y docs/04c_desnormalizacion_justificada.md:
- REGISTRO_PERSONA resuelve la relación N:M entre PERSONA y REGISTRO_PRODUCCION.
- PARO.codigo se conserva aunque subcodigo_id sea NULL.
- La FK compuesta impide asignar un subcódigo de otro código de paro.
- ejecutor_tipo se conserva porque el Excel puede indicar el área sin identificar a una persona.
- meta_por_hora se conserva como valor histórico del registro.
- No se crea TIPO_PARO: el valor "[19] No aplica" se representa con ausencia de filas en PARO.
- No se crea AREA_IMPACTO: el diagnóstico indica que "Área involucrada" en el código 05
  representa OPERARIO/MANTENIMIENTO y corresponde al paro, no a un catálogo de áreas.
*/

CREATE SCHEMA IF NOT EXISTS pascualitos;
SET search_path TO pascualitos, public;

-- 1. Catálogo de máquinas
CREATE TABLE IF NOT EXISTS maquina (
    id_maquina       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(20) NOT NULL UNIQUE
);

-- 2. Catálogo de turnos. Se permiten horarios de distinta duración.
CREATE TABLE IF NOT EXISTS turno (
    id_turno         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion      VARCHAR(40) NOT NULL UNIQUE,
    hora_inicio      TIME,
    hora_fin         TIME
);

-- 3. Personas: seudonimizar; no almacenar nombres reales en esta base analítica.
CREATE TABLE IF NOT EXISTS persona (
    id_persona       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_anonimo   VARCHAR(10) NOT NULL UNIQUE,
    rol              VARCHAR(20) NOT NULL,
    CONSTRAINT ck_persona_rol
        CHECK (rol IN ('OPERARIO', 'MANTENIMIENTO')),
    CONSTRAINT uq_persona_id_rol UNIQUE (id_persona, rol)
);

-- 4. Catálogo de referencias/productos.
-- volumen_cc y num_colores se mantienen separados para evitar texto compuesto.
CREATE TABLE IF NOT EXISTS referencia (
    id_referencia   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto        VARCHAR(80) NOT NULL,
    volumen_cc      INTEGER,
    num_colores     INTEGER,
    CONSTRAINT ck_referencia_volumen
        CHECK (volumen_cc IS NULL OR volumen_cc > 0),
    CONSTRAINT ck_referencia_colores
        CHECK (num_colores IS NULL OR num_colores > 0),
    CONSTRAINT uq_referencia_presentacion
        UNIQUE (producto, volumen_cc, num_colores)
);

-- 5. Catálogo oficial de códigos de paro.
CREATE TABLE IF NOT EXISTS codigo_paro (
    num_codigo      INTEGER PRIMARY KEY,
    descripcion    VARCHAR(150) NOT NULL
);

-- 6. Catálogo jerárquico de subcódigos.
CREATE TABLE IF NOT EXISTS subcodigo (
    id_subcodigo    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_codigo      INTEGER NOT NULL,
    codigo_texto    VARCHAR(10) NOT NULL,
    descripcion    VARCHAR(150) NOT NULL,
    padre_id        INTEGER,
    CONSTRAINT uq_subcodigo_codigo_clave
        UNIQUE (num_codigo, codigo_texto),
    CONSTRAINT uq_subcodigo_codigo_id
        UNIQUE (num_codigo, id_subcodigo),
    CONSTRAINT fk_subcodigo_codigo
        FOREIGN KEY (num_codigo)
        REFERENCES codigo_paro (num_codigo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_subcodigo_padre
        FOREIGN KEY (num_codigo, padre_id)
        REFERENCES subcodigo (num_codigo, id_subcodigo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_subcodigo_no_autopadre
        CHECK (padre_id IS NULL OR padre_id <> id_subcodigo)
);

-- 7. Registro de producción: una fila por formato/registro físico.
-- Los campos que aparecen incompletos en el Excel admiten NULL durante la migración.
CREATE TABLE IF NOT EXISTS registro_produccion (
    id_registro       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha             DATE NOT NULL,
    id_maquina        INTEGER NOT NULL,
    id_turno          INTEGER,
    id_referencia     INTEGER,
    pacas_producidas  INTEGER,
    horas_trabajadas  NUMERIC(6,2),
    meta_por_hora     NUMERIC(10,2),
    observacion_paro  TEXT,
    observaciones     TEXT,
    CONSTRAINT fk_registro_maquina
        FOREIGN KEY (id_maquina)
        REFERENCES maquina (id_maquina)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_registro_turno
        FOREIGN KEY (id_turno)
        REFERENCES turno (id_turno)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_registro_referencia
        FOREIGN KEY (id_referencia)
        REFERENCES referencia (id_referencia)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_registro_pacas
        CHECK (pacas_producidas IS NULL OR pacas_producidas >= 0),
    CONSTRAINT ck_registro_horas
        CHECK (horas_trabajadas IS NULL OR horas_trabajadas >= 0),
    CONSTRAINT ck_registro_meta
        CHECK (meta_por_hora IS NULL OR meta_por_hora > 0)
);

-- 8. Relación N:M: un registro puede tener varias personas responsables.
CREATE TABLE IF NOT EXISTS registro_persona (
    id_registro    BIGINT NOT NULL,
    id_persona     INTEGER NOT NULL,
    PRIMARY KEY (id_registro, id_persona),
    CONSTRAINT fk_registro_persona_registro
        FOREIGN KEY (id_registro)
        REFERENCES registro_produccion (id_registro)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_registro_persona_persona
        FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 9. Detalle de paros asociados a un registro.
CREATE TABLE IF NOT EXISTS paro (
    id_paro             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_registro         BIGINT NOT NULL,
    num_codigo          INTEGER NOT NULL,
    minutos             INTEGER NOT NULL,
    id_subcodigo        INTEGER,
    ejecutor_tipo       VARCHAR(20),
    id_persona_involucrada INTEGER,
    observacion         TEXT,
    CONSTRAINT ck_paro_minutos
        CHECK (minutos > 0),
    CONSTRAINT ck_paro_ejecutor_tipo
        CHECK (ejecutor_tipo IS NULL OR ejecutor_tipo IN ('OPERARIO', 'MANTENIMIENTO')),
    CONSTRAINT ck_paro_persona_requiere_tipo
        CHECK (id_persona_involucrada IS NULL OR ejecutor_tipo IS NOT NULL),
    CONSTRAINT fk_paro_registro
        FOREIGN KEY (id_registro)
        REFERENCES registro_produccion (id_registro)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_paro_codigo
        FOREIGN KEY (num_codigo)
        REFERENCES codigo_paro (num_codigo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_paro_subcodigo_del_mismo_codigo
        FOREIGN KEY (num_codigo, id_subcodigo)
        REFERENCES subcodigo (num_codigo, id_subcodigo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_paro_persona_rol
        FOREIGN KEY (id_persona_involucrada, ejecutor_tipo)
        REFERENCES persona (id_persona, rol)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Índices para filtros y JOIN frecuentes.
CREATE INDEX IF NOT EXISTS ix_registro_fecha
    ON registro_produccion (fecha);
CREATE INDEX IF NOT EXISTS ix_registro_maquina_fecha
    ON registro_produccion (id_maquina, fecha);
CREATE INDEX IF NOT EXISTS ix_registro_turno_fecha
    ON registro_produccion (id_turno, fecha);
CREATE INDEX IF NOT EXISTS ix_paro_codigo
    ON paro (num_codigo);
CREATE INDEX IF NOT EXISTS ix_paro_registro
    ON paro (id_registro);
CREATE INDEX IF NOT EXISTS ix_paro_subcodigo
    ON paro (id_subcodigo);

-- Comprobación rápida de que se crearon las tablas.
SELECT table_schema, table_name
FROM information_schema.tables
WHERE table_schema = 'pascualitos'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;
